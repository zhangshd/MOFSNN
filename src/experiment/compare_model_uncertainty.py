def extract_model_name_from_path(path: Union[str, Path]) -> str:
    """
    Extract a readable model name from the path.
    
    Args:
        path: Path to the model's uncertainty evolution CSV file
        
    Returns:
        Cleaned model name string
    """
    path = Path(path)
    # Get the parent directory name as the model name
    model_name = path.parent.name
    
    # Clean up the model name if needed
    # Remove common prefixes or suffixes
    model_name = model_name.replace('analysis', '')
    
    # Handle special case for nested directories
    if 'analysis' in str(path.parent):
        # Get the grandparent directory
        model_name = path.parent.parent.name
    
    return model_name


def load_uncertainty_data(file_path: Union[str, Path], model_name_map: Dict[str, str]) -> pd.DataFrame:
    """
    Load uncertainty data from a CSV file and add model identifier.
    
    Args:
        file_path: Path to the CSV file
        
    Returns:
        DataFrame with uncertainty data including model identifier
    """
    df = pd.DataFrame()
    try:
        df = pd.read_csv(file_path)
        # Add model name to the DataFrame
        model_name = extract_model_name_from_path(file_path)
        df['model'] = model_name_map[model_name]
        
        # Check if 'is_best_epoch' column exists, if not add it with False values
        if 'is_best_epoch' not in df.columns:
            df['is_best_epoch'] = False
            
    except Exception as e:
        print(f"Error loading {file_path}: {e}")
    
    return df


def find_uncertainty_csv_files(
    model_result_dirs: List[Union[str, Path]],
    task_name: str,
    split: str = 'val',
    uncertainty_type: Optional[str] = None
) -> List[Path]:
    """
    Find all uncertainty evolution CSV files for a specific task and split across model results.
    
    Args:
        model_result_dirs: List of directories containing model results
        task_name: Name of the task to find files for
        split: Data split to analyze ('train', 'val', or 'test')
        uncertainty_type: Type of uncertainty to find ('LSV' or 'LSE'), if None, will find any
        
    Returns:
        List of paths to matching CSV files
    """
    matching_files = []
    
    for dir_path in model_result_dirs:
        dir_path = Path(dir_path)
        
        # First try looking in the 'analysis' subdirectory
        analysis_dir = dir_path / "analysis"
        if not analysis_dir.exists():
            # If no analysis directory, try using the directory itself
            analysis_dir = dir_path
        
        # Build pattern based on parameters
        if uncertainty_type:
            pattern = f"{task_name}_{uncertainty_type}_{split}_evolution.csv"
        else:
            pattern = f"{task_name}_*_{split}_evolution.csv"
        
        # Find matching files
        for file_path in analysis_dir.glob(pattern):
            matching_files.append(file_path)
    
    return matching_files


def compare_uncertainty_evolution(
    model_result_dirs: List[Union[str, Path]],
    model_name_map: Dict[str, str],
    task_name: str,
    output_dir: Union[str, Path],
    split: str = 'val',
    uncertainty_type: Optional[str] = None,
    best_epoch_marker: bool = True,
    output_filename: Optional[str] = None
) -> Optional[pd.DataFrame]:
    """
    Compare the uncertainty evolution of different models for the same task and data split.
    
    Args:
        model_result_dirs: List of directories containing model results
        task_name: Name of the task to compare
        output_dir: Directory to save comparison plots
        split: Data split to analyze ('train', 'val', or 'test')
        uncertainty_type: Type of uncertainty to compare ('LSV' or 'LSE'), if None, will be determined from files
        best_epoch_marker: Whether to mark best epochs in the plot
        output_filename: Custom filename for the output plot, if None will generate automatically
        
    Returns:
        Combined DataFrame with all model data, or None if no data found
    """
    # Create output directory
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Find matching CSV files
    csv_files = find_uncertainty_csv_files(model_result_dirs, task_name, split, uncertainty_type)
    
    if not csv_files:
        print(f"No matching CSV files found for task '{task_name}', split '{split}'")
        return None
    
    print(f"Found {len(csv_files)} matching CSV files for task '{task_name}', split '{split}'")
    
    # Load and combine data from all files
    all_data = []
    actual_uncertainty_type = None
    
    for file_path in csv_files:
        # Determine actual uncertainty type from filename if not specified
        if uncertainty_type is None:
            match = re.search(r'_(LSV|LSE)_', file_path.name)
            if match:
                file_uncertainty_type = match.group(1)
                if actual_uncertainty_type is None:
                    actual_uncertainty_type = file_uncertainty_type
                elif actual_uncertainty_type != file_uncertainty_type:
                    print(f"Warning: Mixed uncertainty types found. Expected {actual_uncertainty_type} but found {file_uncertainty_type} in {file_path}")
                    continue
        
        # Load data
        df = load_uncertainty_data(file_path, model_name_map)
        if not df.empty:
            all_data.append(df)
    
    if not all_data:
        print(f"No valid data found for task '{task_name}', split '{split}'")
        return None
    
    # Combine all data
    combined_df = pd.concat(all_data, ignore_index=True)
    
    # Use the determined uncertainty type if none was specified
    if uncertainty_type is None:
        uncertainty_type = actual_uncertainty_type
    
    # Generate plot
    plt.figure(figsize=(12, 8))
    
    # Use distinct colors, line styles, and markers for different models
    line_styles = ['-', '--', '-.', ':']
    markers = ['o', 's', '^', 'x', 'D', '*', 'p', 'v', '<', '>']
    
    # Get unique models
    unique_models = combined_df['model'].unique()
    
    # Create a mapping for best epochs
    best_epochs = {}
    
    # Plot data for each model
    for i, model in enumerate(unique_models):
        model_data = combined_df[combined_df['model'] == model]
        
        # Sort by epoch
        model_data = model_data.sort_values('epoch')
        
        # Plot line
        line_style = line_styles[i % len(line_styles)]
        marker = markers[i % len(markers)]
        
        plt.plot(
            model_data['epoch'], 
            model_data['uncertainty'], 
            linestyle=line_style,
            marker=marker,
            markersize=8,
            markevery=max(1, len(model_data) // 10),  # Show marker every ~10 points
            alpha=0.8,
            label=model
        )
        
        # Find best epoch if marked
        if best_epoch_marker and 'is_best_epoch' in model_data.columns:
            best_epoch_rows = model_data[model_data['is_best_epoch']]
            if not best_epoch_rows.empty:
                best_epoch = int(best_epoch_rows['epoch'].iloc[0])
                best_uncertainty = float(best_epoch_rows['uncertainty'].iloc[0])
                best_epochs[model] = (best_epoch, best_uncertainty)
    
    # Mark best epochs with special markers
    if best_epoch_marker and best_epochs:
        # Create a separate plot entry for the best epoch legend
        has_legend_entry = False
        
        for model, (epoch, uncertainty) in best_epochs.items():
            # Plot a large distinctive marker at the best epoch point for each model
            if not has_legend_entry:
                # Only add to legend once
                plt.plot(
                    epoch, 
                    uncertainty,
                    marker='*',  # Star marker for best epochs
                    markersize=16,  # Larger size
                    markerfacecolor='gold',  # Gold color for all best epoch markers
                    markeredgecolor='black',
                    markeredgewidth=1.5,
                    linestyle='None',  # No line, just the marker
                    label='Best Epoch'
                )
                has_legend_entry = True
            else:
                # Don't add to legend for subsequent models
                plt.plot(
                    epoch, 
                    uncertainty,
                    marker='*',  # Star marker for best epochs
                    markersize=16,  # Larger size
                    markerfacecolor='gold',  # Gold color for all best epoch markers
                    markeredgecolor='black',
                    markeredgewidth=1.5,
                    linestyle='None'  # No line, just the marker
                )
            
            # Add a text annotation with the epoch number
            plt.annotate(
                f'{model}',
                xy=(epoch, uncertainty),
                xytext=(5, 5),  # Offset text slightly
                textcoords='offset points',
                fontsize=8,
                fontweight='normal',
                bbox=dict(boxstyle="round,pad=0.3", fc="white", ec="gray", alpha=0.8)
            )
    
    # Set plot title and labels
    split_names = {'train': 'Training', 'val': 'Validation', 'test': 'Test'}
    split_name = split_names.get(split, split.capitalize())
    
    plt.title(f'{uncertainty_type} Evolution for Task "{task_name}" ({split_name} Set)', fontsize=14)
    plt.xlabel('Epoch', fontsize=12)
    plt.ylabel(f'Average {uncertainty_type}', fontsize=12)
    plt.grid(True, linestyle='--', alpha=0.7)
    
    # Add legend with better formatting
    plt.legend(loc='best', fontsize=10, framealpha=0.7, fancybox=True, frameon=True)
    
    # Save figure
    if output_filename:
        output_file = output_dir / output_filename
    else:
        output_file = output_dir / f"model_comparison_{task_name}_{uncertainty_type}_{split}.png"
    
    plt.tight_layout()
    plt.savefig(output_file, dpi=300, bbox_inches='tight')
    print(f"Saved comparison plot to {output_file}")
    plt.close()
    
    # Save combined data to CSV
    csv_output = output_file.with_suffix('.csv')
    combined_df.to_csv(csv_output, index=False)
    print(f"Saved combined data to {csv_output}")
    
    return combined_df


def get_available_tasks(model_result_dirs: List[Union[str, Path]]) -> Set[str]:
    """
    Find all available tasks in the model result directories.
    
    Args:
        model_result_dirs: List of directories containing model results
        
    Returns:
        Set of available task names
    """
    tasks = set()
    
    for dir_path in model_result_dirs:
        dir_path = Path(dir_path)
        
        # Check in the 'analysis' subdirectory if it exists
        analysis_dir = dir_path / "analysis"
        if not analysis_dir.exists():
            analysis_dir = dir_path
        
        # Find all CSV files matching the pattern
        for file_path in analysis_dir.glob("*_evolution.csv"):
            match = re.search(r'^(.+?)_(LSV|LSE)_(train|val|test)_evolution\.csv$', file_path.name)
            if match:
                task_name = match.group(1)
                tasks.add(task_name)
    
    return tasks


