from cgcnn.module.module_utils import calculate_lse_from_tree, calculate_lsv_from_tree


def extract_epoch_from_dir(directory: Union[str, Path]) -> Optional[int]:
    """
    Extract epoch number from directory name.
    
    Args:
        directory: Directory path, expected to contain 'epoch_XXX' pattern
        
    Returns:
        Extracted epoch number or None if not found
    """
    match = re.search(r'epoch_(\d+)', str(directory))
    if match:
        return int(match.group(1))
    return None


def track_uncertainty_evolution(
    checkpoints_dir: Union[str, Path], 
    output_dir: Union[str, Path],
    patience: int = 50  # Add patience parameter with default value 50
) -> Dict[str, Dict[str, List[Tuple[int, float]]]]:
    """
    Track the evolution of uncertainty metrics during model training using
    pre-computed uncertainty trees and feature vectors from build_latent_vec_tree.py.
    
    Args:
        checkpoints_dir: Directory containing processed checkpoint directories 
                        (from build_latent_vec_tree.py)
        output_dir: Directory to save output analysis results
        patience: Early stopping patience value (default: 50)
        
    Returns:
        Dictionary with uncertainty results for each task and data split
    """
    # Create output directory
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    
    # Find all processed epoch directories
    checkpoints_dir = Path(checkpoints_dir)
    epoch_dirs = sorted([d for d in checkpoints_dir.glob("epoch_*") if d.is_dir()], 
                       key=extract_epoch_from_dir)
    
    if not epoch_dirs:
        print(f"No epoch directories found in {checkpoints_dir}")
        return {}
    
    print(f"Found {len(epoch_dirs)} epoch directories")
    
    # Get the first directory to determine available tasks
    first_dir = epoch_dirs[0]
    uncertainty_trees_file = first_dir / "uncertainty_trees.pkl"
    
    if not uncertainty_trees_file.exists():
        print(f"No uncertainty_trees.pkl found in {first_dir}")
        return {}
    
    with open(uncertainty_trees_file, 'rb') as f:
        uncertainty_trees = pickle.load(f)
    
    # Initialize results storage
    tasks = list(uncertainty_trees.keys())
    # Add 'train' split to results dictionary
    results = {task: {'train': [], 'val': [], 'test': []} for task in tasks}
    task_types = {task: uncertainty_trees[task]["task_type"] for task in tasks}
    epochs = []
    
    # Process each epoch directory
    for epoch_dir in epoch_dirs:
        epoch = extract_epoch_from_dir(epoch_dir)
        if epoch is None:
            print(f"Could not extract epoch number from {epoch_dir}, skipping")
            continue
        
        epochs.append(epoch)
        print(f"\nProcessing results from epoch {epoch}")
        
        # Load uncertainty trees for this epoch
        uncertainty_trees_file = epoch_dir / "uncertainty_trees.pkl"
        if not uncertainty_trees_file.exists():
            print(f"No uncertainty_trees.pkl found in {epoch_dir}, skipping")
            continue
            
        with open(uncertainty_trees_file, 'rb') as f:
            uncertainty_trees = pickle.load(f)
        
        # Process each task for all splits: train, validation and test sets
        for task in tasks:
            if task not in uncertainty_trees:
                print(f"Task {task} not found in uncertainty trees for epoch {epoch}, skipping")
                continue
                
            task_type = task_types[task]
            
            # Process all sets (train, validation, test)
            for split in ['train', 'val', 'test']:
                # Load the feature vectors for this split
                features_file = epoch_dir / f"{task}_{split}_latent_vectors.npz"
                if not features_file.exists():
                    print(f"No feature file found for task {task}, split {split}, epoch {epoch}, skipping")
                    continue
                
                # Load features
                features_data = np.load(features_file)
                features = features_data['features']
                
                # Calculate uncertainty based on task type
                if "classification" in task_type:
                    uncertainties = calculate_lse_from_tree(
                        uncertainty_trees[task], 
                        features, 
                        k=uncertainty_trees[task]["k"]
                    )
                else:
                    uncertainties = calculate_lsv_from_tree(
                        uncertainty_trees[task], 
                        features, 
                        k=uncertainty_trees[task]["k"]
                    )
                
                # Calculate average uncertainty
                mean_uncertainty = np.mean(uncertainties)
                results[task][split].append((epoch, mean_uncertainty))
                print(f"  Task {task} average uncertainty on {split} set: {mean_uncertainty:.4f}")
    
    # Calculate best epoch (last epoch - patience)
    max_epoch = max(epochs) if epochs else 0
    best_epoch = max(0, max_epoch - patience)  # Ensure best_epoch is not negative
    print(f"\nLast epoch: {max_epoch}, Early stopping patience: {patience}")
    print(f"Estimated best epoch: {best_epoch}")
    
    # Create visualizations
    for task in tasks:
        task_type = task_types[task]
        uncertainty_type = "LSE" if "classification" in task_type else "LSV"
        
        # Check if we have data
        has_data = False
        for split in ['train', 'val', 'test']:
            if results[task][split]:
                has_data = True
                break
                
        if not has_data:
            print(f"No results for task {task}. Skipping visualization.")
            continue
        
        plt.figure(figsize=(10, 6))
        
        # Plot all data sets with alpha=0.8 for transparency
        split_colors = {'train': 'g', 'val': 'b', 'test': 'r'}
        split_markers = {'train': '^', 'val': 'o', 'test': 'x'}
        split_labels = {'train': 'Training Set', 'val': 'Validation Set', 'test': 'Test Set'}
        
        for split in ['train', 'val', 'test']:
            if not results[task][split]:
                continue
                
            epochs, uncertainties = zip(*sorted(results[task][split]))
            plt.plot(
                epochs, 
                uncertainties, 
                f"{split_colors[split]}-", 
                marker=split_markers[split], 
                label=split_labels[split],
                alpha=0.8  # Set transparency to 0.8
            )
        
        # Add vertical line for best epoch
        if best_epoch in epochs:
            plt.axvline(x=best_epoch, color='k', linestyle='--', alpha=0.7, 
                       label=f'Best Epoch ({best_epoch})')
            
            # Add annotation for best epoch
            # y_min, y_max = plt.ylim()
            # y_pos = y_min + 0.9 * (y_max - y_min)  # Position text at 90% of y-axis
            # plt.annotate(f'Best Epoch: {best_epoch}',
            #             xy=(best_epoch, y_pos),
            #             xytext=(best_epoch + 5, y_pos),  # Offset text slightly
            #             arrowprops=dict(arrowstyle="->", connectionstyle="arc3,rad=.2"),
            #             bbox=dict(boxstyle="round,pad=0.3", fc="yellow", alpha=0.3))
        
        plt.title(f'Average {uncertainty_type} for {task} during Training')
        plt.xlabel('Epoch')
        plt.ylabel(f'Average {uncertainty_type}')
        plt.legend()
        plt.grid(True, linestyle='--', alpha=0.7)
        
        # Save figure
        output_file = output_dir / f"{task}_{uncertainty_type}_evolution.png"
        plt.savefig(output_file, dpi=300, bbox_inches='tight')
        plt.close()
        print(f"Saved {task} uncertainty evolution plot to {output_file}")
        
        # Save data to CSV
        for split in ['train', 'val', 'test']:
            if results[task][split]:
                df = pd.DataFrame(sorted(results[task][split]), columns=['epoch', 'uncertainty'])
                # Add best epoch information to the DataFrame
                df['is_best_epoch'] = df['epoch'] == best_epoch
                df.to_csv(output_dir / f"{task}_{uncertainty_type}_{split}_evolution.csv", index=False)
    
    # Separate tasks by type for dual y-axis plotting
    regression_tasks = [task for task in tasks if "classification" not in task_types[task]]
    classification_tasks = [task for task in tasks if "classification" in task_types[task]]
    
    # Create combined plots with dual y-axes for different data splits
    for split in ['train', 'val', 'test']:
        # Check if we have both types of tasks for this split
        has_regression = any(len(results[task][split]) > 0 for task in regression_tasks)
        has_classification = any(len(results[task][split]) > 0 for task in classification_tasks)
        
        if not (has_regression and has_classification):
            # Create standard combined plot if we don't need dual y-axes
            plt.figure(figsize=(12, 8))
            line_styles = ['-', '--', '-.', ':']
            markers = ['o', 's', '^', 'x', 'D', '*']
            
            for i, task in enumerate(tasks):
                task_type = task_types[task]
                uncertainty_type = "LSE" if "classification" in task_type else "LSV"
                
                if not results[task][split]:
                    continue
                
                plot_epochs, plot_uncertainties = zip(*sorted(results[task][split]))
                plt.plot(
                    plot_epochs, plot_uncertainties, 
                    linestyle=line_styles[i % len(line_styles)],
                    marker=markers[i % len(markers)],
                    label=f'{task} ({uncertainty_type})',
                    alpha=0.8  # Set transparency to 0.8
                )
            
            # Add vertical line for best epoch
            if best_epoch in epochs:
                plt.axvline(x=best_epoch, color='k', linestyle='--', alpha=0.7, 
                           label=f'Best Epoch ({best_epoch})')
                
            #     # Add annotation for best epoch
            #     y_min, y_max = plt.ylim()
            #     y_pos = y_min + 0.9 * (y_max - y_min)
            #     plt.annotate(f'Best Epoch: {best_epoch}',
            #                 xy=(best_epoch, y_pos),
            #                 xytext=(best_epoch + 5, y_pos),
            #                 arrowprops=dict(arrowstyle="->", connectionstyle="arc3,rad=.2"),
            #                 bbox=dict(boxstyle="round,pad=0.3", fc="yellow", alpha=0.3))
            
            plt.title(f'Uncertainty Evolution for All Tasks ({split_labels[split]})')
            plt.xlabel('Epoch')
            plt.ylabel('Average Uncertainty')
            plt.legend()
            plt.grid(True, linestyle='--', alpha=0.7)
            
            combined_output_file = output_dir / f"all_tasks_uncertainty_evolution_{split}.png"
            plt.savefig(combined_output_file, dpi=300, bbox_inches='tight')
            plt.close()
            print(f"Saved combined uncertainty evolution plot to {combined_output_file}")
        else:
            # Create dual y-axis plot
            fig, ax1 = plt.subplots(figsize=(14, 8))
            ax2 = ax1.twinx()  # Create a second y-axis
            
            line_styles = ['-', '--', '-.', ':']
            markers = ['o', 's', '^', 'x', 'D', '*']
            lines1 = []  # For regression tasks (LSV)
            lines2 = []  # For classification tasks (LSE)
            labels = []  # Combined labels for both types
            
            # Plot regression tasks on left y-axis
            for i, task in enumerate(regression_tasks):
                if not results[task][split]:
                    continue
                    
                plot_epochs, plot_uncertainties = zip(*sorted(results[task][split]))
                line, = ax1.plot(
                    plot_epochs, plot_uncertainties, 
                    linestyle=line_styles[i % len(line_styles)],
                    marker=markers[i % len(markers)],
                    color=plt.cm.tab10(i),
                    alpha=0.8  # Set transparency to 0.8
                )
                lines1.append(line)
                labels.append(f'{task} (LSV)')
            
            # Plot classification tasks on right y-axis
            for i, task in enumerate(classification_tasks):
                if not results[task][split]:
                    continue
                    
                plot_epochs, plot_uncertainties = zip(*sorted(results[task][split]))
                line, = ax2.plot(
                    plot_epochs, plot_uncertainties, 
                    linestyle=line_styles[i % len(line_styles)],
                    marker=markers[(i + len(regression_tasks)) % len(markers)],
                    color=plt.cm.tab10(i + len(regression_tasks)),
                    alpha=0.8  # Set transparency to 0.8
                )
                lines2.append(line)
                labels.append(f'{task} (LSE)')
            
            # Add vertical line for best epoch on both axes
            if best_epoch in epochs:
                line_best = ax1.axvline(x=best_epoch, color='k', linestyle='--', alpha=0.7)
                
                # Add annotation for best epoch
                # y_min, y_max = ax1.get_ylim()
                # y_pos = y_min + 0.9 * (y_max - y_min)
                # ax1.annotate(f'Best Epoch: {best_epoch}',
                #             xy=(best_epoch, y_pos),
                #             xytext=(best_epoch + 5, y_pos),
                #             arrowprops=dict(arrowstyle="->", connectionstyle="arc3,rad=.2"),
                #             bbox=dict(boxstyle="round,pad=0.3", fc="yellow", alpha=0.3))
                
                # Add best epoch to legend
                lines2.append(line_best)
                labels.append(f'Best Epoch ({best_epoch})')
            
            # Set labels and title
            ax1.set_xlabel('Epoch')
            ax1.set_ylabel('Average LSV (Regression)', color='tab:blue', fontsize=12)
            ax2.set_ylabel('Average LSE (Classification)', color='tab:red', fontsize=12)
            plt.title(f'Uncertainty Evolution for All Tasks ({split_labels[split]})')
            
            # Add combined legend
            all_lines = lines1 + lines2
            plt.legend(all_lines, labels, loc='upper center', bbox_to_anchor=(0.5, -0.12), 
                       fancybox=True, shadow=True, ncol=3)
            
            # Set grid
            ax1.grid(True, linestyle='--', alpha=0.7)
            
            # Adjust layout to fit the legend
            plt.tight_layout()
            plt.subplots_adjust(bottom=0.2)
            
            # Save figure
            combined_output_file = output_dir / f"all_tasks_dual_axis_uncertainty_evolution_{split}.png"
            plt.savefig(combined_output_file, dpi=300, bbox_inches='tight')
            plt.close()
            print(f"Saved dual-axis combined uncertainty evolution plot to {combined_output_file}")
    
    return results


